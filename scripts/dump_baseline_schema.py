"""Dump the current schema as the single baseline migration.

The repository builds a fresh database from ``storage/schema_baseline.sql``.
Regenerate that file with this tool after any schema change, then bump
``migrations_baseline.BASELINE_VERSION``.

Usage::

    python scripts/dump_baseline_schema.py

The output contains every table, index and trigger from a freshly initialized
database, plus the singleton rows that migrations seed (state tables and the
embedding read-cache revision). FTS shadow tables are omitted: creating the
virtual table recreates them.

The script deliberately has no BEGIN/COMMIT and no ``PRAGMA user_version``:
``apply_migration`` wraps it in a transaction and sets the version itself.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import sqlite3
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from fxi_novel.storage.database import Database  # noqa: E402

_FTS_SHADOW_SUFFIXES = ("_data", "_idx", "_content", "_docsize", "_config")
_SINGLETON_TABLES = (
    "embedding_read_cache_revision",
    "knowledge_graph_fts_state",
    "knowledge_card_index_state",
    "knowledge_source_title_search_state",
    "knowledge_card_candidate_evidence_state",
    "knowledge_card_folder_summary_state",
)


def _is_fts_shadow(name: str) -> bool:
    return "_fts" in name and name.endswith(_FTS_SHADOW_SUFFIXES)


def _quote(identifier: str) -> str:
    return '"' + identifier.replace('"', '""') + '"'


def _insert_rows(connection: sqlite3.Connection, table: str) -> list[str]:
    columns = [str(row[1]) for row in connection.execute(f"PRAGMA table_info({_quote(table)})")]
    rows = connection.execute(f"SELECT * FROM {_quote(table)}").fetchall()
    statements = []
    for row in rows:
        values = []
        for value in row:
            if value is None:
                values.append("NULL")
            elif isinstance(value, (int, float)):
                values.append(repr(value))
            elif isinstance(value, bytes):
                values.append("X'" + value.hex() + "'")
            else:
                escaped = str(value).replace("'", "''")
                values.append("'" + escaped + "'")
        statements.append(
            f"INSERT INTO {_quote(table)} ({', '.join(_quote(column) for column in columns)}) "
            f"VALUES ({', '.join(values)});"
        )
    return statements


def dump_schema() -> str:
    database = Database(":memory:")
    database.initialize()
    try:
        with database.connection() as connection:
            version = int(connection.execute("PRAGMA user_version").fetchone()[0])
            rows = connection.execute(
                "SELECT type, name, sql FROM sqlite_master "
                "WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'"
            ).fetchall()
            objects: dict[str, list[tuple[str, str]]] = {"table": [], "index": [], "trigger": []}
            for kind, name, sql in rows:
                if kind not in objects or _is_fts_shadow(str(name)):
                    continue
                objects[kind].append((str(name), str(sql)))
            statements = [
                sql.rstrip().rstrip(";") + ";"
                for kind in ("table", "index", "trigger")
                for _, sql in objects[kind]
            ]
            for table in _SINGLETON_TABLES:
                exists = connection.execute(
                    "SELECT 1 FROM sqlite_master WHERE type='table' AND name=?", (table,)
                ).fetchone()
                if exists:
                    statements.extend(_insert_rows(connection, table))
    finally:
        database.close()

    header = [
        "-- Baseline schema draft generated by scripts/dump_baseline_schema.py.",
        f"-- Source schema version: {version}",
        "-- Replace the migration chain only after the validation steps in",
        "-- docs/migration-squash-plan.md pass.",
        "",
    ]
    return "\n".join([*header, *statements, ""])


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=ROOT / "build" / "migration-baseline-draft.sql",
        help="where to write the draft SQL",
    )
    args = parser.parse_args()
    sql = dump_schema()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(sql, encoding="utf-8")
    statements = sum(1 for line in sql.splitlines() if line.endswith(";"))
    print(f"wrote {args.output} ({len(sql):,} chars, {statements} statements)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
